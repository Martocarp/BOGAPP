const router = require('express').Router();
const c = require('../controllers/profesionalController');
const p = require('../controllers/participacionController');
const { autenticar, permitirRoles } = require('../middlewares/authMiddleware');
const { upload } = require('../helpers/archivos');
router.use(autenticar, permitirRoles('PROFESIONAL'));
router.get('/perfil', c.perfil);
router.put('/perfil', c.editarPerfil);
router.post('/perfil/cv', upload.single('archivo'), c.subirCv);
router.get('/perfil/cv', c.bajarCv);
router.delete('/perfil/cv', c.borrarCv);
router.get('/clientes', c.clientes);
router.get('/clientes-elegibles', c.clientesElegibles);
router.get('/buscar-cliente', c.buscarCliente);
router.post('/clientes/invitar', c.invitarParticular);
router.post('/estudios/:id/clientes/invitar', c.invitarEstudio);
router.get('/estudios/:id/profesionales', c.miembros);
router.get('/dashboard', c.dashboard);
router.get('/buscar-profesional', p.buscarProfesional);
router.get('/invitaciones', p.invitaciones);
router.post('/estudios/:id/invitar', p.invitar);
router.post('/estudios/:id/solicitar-ingreso', p.solicitarIngreso);
router.patch('/invitaciones/:id', p.responderInvitacion);
router.get('/estudios/:id/solicitudes', p.pendientes);
router.patch('/estudios/:id/solicitudes/:usuarioId', p.responderSolicitud);
module.exports = router;
